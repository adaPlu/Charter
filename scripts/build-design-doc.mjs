// Builds docs/charter-design.md from the parts in docs/design/, in filename order, with a
// table of contents. Output depends only on the parts, so CI can check it is up to date.
// Usage: node scripts/build-design-doc.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const partsDir = join(root, "docs", "design");
const outPath = join(root, "docs", "charter-design.md");

const parts = readdirSync(partsDir).filter((f) => f.endsWith(".md")).sort();
const bodies = parts.map((f) => readFileSync(join(partsDir, f), "utf8").replace(/\r\n/g, "\n").trimEnd());

// GitHub-style heading anchors, de-duplicated the way GitHub does it.
const used = new Map();
const slug = (text) => {
  const base = text.toLowerCase().replace(/[`*_]/g, "").replace(/[^\p{L}\p{N}\s-]/gu, "").trim().replace(/\s/g, "-");
  const n = used.get(base) ?? 0;
  used.set(base, n + 1);
  return n === 0 ? base : `${base}-${n}`;
};

const toc = [];
bodies.forEach((body, partIndex) => {
  let fence = false;
  for (const line of body.split("\n")) {
    if (/^(```|~~~)/.test(line)) { fence = !fence; continue; }
    if (fence) continue;
    const m = /^(#{1,2}) (.+)$/.exec(line);
    if (!m) continue;
    const anchor = slug(m[2]); // computed for every heading, so duplicate numbering matches GitHub
    if (partIndex === 0) continue; // the front matter sits above the contents
    toc.push(`${m[1].length === 1 ? "" : "  "}- [${m[2].replace(/[`*]/g, "")}](#${anchor})`);
  }
});

const [front, ...rest] = bodies;
const out = [
  "<!-- Generated by scripts/build-design-doc.mjs from docs/design/*.md. Edit the parts, not this file. -->",
  "",
  front,
  "",
  "## Contents",
  "",
  ...toc,
  "",
  ...rest.flatMap((b) => ["---", "", b, ""]),
].join("\n");

writeFileSync(outPath, out.trimEnd() + "\n");
const words = out.split(/\s+/).filter(Boolean).length;
console.log(`build-design-doc: wrote docs/charter-design.md (${parts.length} parts, ${toc.length} contents entries, about ${words.toLocaleString("en-US")} words)`);
