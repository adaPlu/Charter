// Writes the packet an independent reviewer works from: every pilot task's request, contract and
// tests, with no solution in either language. Phase 7 requires tasks written and reviewed
// independently of the language's design; this packet is what that person reads.
//
//   node bench/harness/review-packet.ts            writes bench/review/packet.md and verdicts.md
//   node bench/harness/review-packet.ts --check    fails if packet.md is out of date (CI)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { loadTasks, contractText, testText } from "./tasks.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const outDir = join(root, "bench", "review");
const tasks = loadTasks(root).filter((t) => !t.validationOnly);

const families: Record<string, string> = {
  F1: "Computation", F2: "Records you create, read, change and delete", F3: "Who may do what",
  F4: "Money-like balances that must never go wrong", F5: "Workflows with steps and states", F6: "Outside Charter's intended domain",
};

const packet: string[] = [
  "# H1 pilot tasks: review packet",
  "",
  "Generated by `node bench/harness/review-packet.ts`. Do not edit by hand; edit `bench/tasks/<id>/task.json` and regenerate.",
  "",
  "Each task is what a model is asked to build, in both TypeScript and Charter. The model sees the request, the contract and the tests marked *visible*. The other tests are hidden and decide whether its program works. Read `bench/review/README.md` first.",
  "",
  `${tasks.length} tasks, ${tasks.reduce((n, t) => n + t.tests.length, 0)} test scenarios.`,
  "",
];
for (const t of tasks) {
  packet.push(`## ${t.id}`, "", `**Family:** ${t.family}, ${families[t.family] ?? ""}`, "", "**Request**", "", `> ${t.request}`, "");
  packet.push("**Contract**", "", "```text", contractText(t), "```", "");
  packet.push("**Tests**", "", "`$name` is a value saved by an earlier step.", "", "```text");
  for (const test of t.tests) packet.push(testText(test, t.visibleTests.includes(test.name) ? "[visible] " : "[hidden]  "), "");
  packet.push("```", "");
}
const packetText = packet.join("\n");

const packetPath = join(outDir, "packet.md");
if (process.argv.includes("--check")) {
  if (!existsSync(packetPath) || readFileSync(packetPath, "utf8") !== packetText) {
    console.error("review-packet: bench/review/packet.md is out of date; run node bench/harness/review-packet.ts");
    process.exit(1);
  }
  console.log(`review-packet: ok (${tasks.length} tasks)`);
} else {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(packetPath, packetText);
  const verdictsPath = join(outDir, "verdicts.md");
  if (!existsSync(verdictsPath)) {
    // The reviewer's answer sheet. Never overwritten once it exists.
    const v = [
      "# Review verdicts",
      "",
      "Reviewer name: ",
      "Date: ",
      "Has the reviewer seen Charter's design or any solution to these tasks? (yes / no): ",
      "",
      "For each task: **Approve**, **Edit** (say what), or **Replace** (write the new task, or say why it should go).",
      "",
      "| Task | Verdict | Notes |",
      "|---|---|---|",
      ...tasks.map((t) => `| ${t.id} |  |  |`),
      "",
    ];
    writeFileSync(verdictsPath, v.join("\n"));
  }
  console.log(`review-packet: wrote bench/review/packet.md (${tasks.length} tasks)`);
}
